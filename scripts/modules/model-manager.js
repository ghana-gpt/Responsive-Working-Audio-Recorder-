/**
 * Speech-model manager: download, verify, cache and inspect the Whisper files.
 *
 * The model is published as a versioned release asset and the site serves it
 * from `models/whisper-tiny/`. Until those files are on the device, a source
 * checkout or a brand-new install cannot transcribe offline. This module gives
 * the UI a way to prepare that copy *from the browser*: it reads the same
 * `model-package.json` the build verifies against, downloads every file with
 * byte progress (cancellable), checks the SHA-256 of each one, and stores the
 * verified bytes in the service worker's model cache so the worker's normal
 * `fetch` calls are served locally from then on.
 *
 * Nothing here talks to a third party: the manifest and the files come from the
 * app's own origin (GitHub Pages or the dev server), which is what the CSP and
 * the offline promise allow.
 *
 * The pure helpers (`parseManifest`, `manifestFiles`, `sha256Hex`, …) are
 * exported so they can be unit tested in Node; the cache is injected, so tests
 * never need a real CacheStorage.
 */

import { AsrError } from './asr.js';

/** Cache that survives app updates (must match `MODEL_CACHE` in the SW). */
export const MODEL_CACHE_NAME = 'audio-recorder-model-whisper-tiny-v1';

/** Scratch cache Transformers.js uses for the model files it fetches itself. */
export const MODEL_RUNTIME_CACHE = 'transformers-cache';

/** The build's manifest, served from the site root. */
export const MODEL_MANIFEST_URL = new URL('../../model-package.json', import.meta.url).href;

/** Folder that holds the model files. */
export const MODEL_FILES_URL = new URL('../../models/whisper-tiny/', import.meta.url).href;

/** Extra room kept free so a cached model cannot fill the whole quota. */
const SPACE_MARGIN_BYTES = 8 * 1024 * 1024;

const SHA256 = /^[0-9a-f]{64}$/i;

/**
 * Resolve a manifest path against the model folder.
 *
 * @param {string} path
 * @param {string} [root]
 * @returns {string} absolute URL
 */
export function modelFileUrl(path, root = MODEL_FILES_URL) {
  return new URL(path, root).href;
}

/**
 * Validate and normalise the manifest.
 *
 * The file is generated by `npm run models:package`, but it is also fetched at
 * runtime, so a truncated or hand-edited copy must fail loudly instead of
 * producing a half-verified cache.
 *
 * @param {unknown} raw parsed JSON
 * @returns {{ name: string, version: string, modelBytes: number, files: Record<string, { bytes: number, sha256: string }> }}
 */
export function parseManifest(raw) {
  const manifest = raw && typeof raw === 'object' ? raw : null;
  if (!manifest) {
    throw new AsrError('modelManifestInvalid', 'The model manifest is not an object');
  }
  const files = manifest.files;
  if (!files || typeof files !== 'object' || Array.isArray(files)) {
    throw new AsrError('modelManifestInvalid', 'The model manifest has no file list');
  }

  const clean = {};
  let total = 0;
  for (const [path, entry] of Object.entries(files)) {
    const bytes = Number(entry?.bytes);
    const sha256 = String(entry?.sha256 ?? '');
    if (!path || !Number.isFinite(bytes) || bytes <= 0) {
      throw new AsrError('modelManifestInvalid', `The manifest entry for “${path}” has no size`);
    }
    if (!SHA256.test(sha256)) {
      throw new AsrError(
        'modelManifestInvalid',
        `The manifest entry for “${path}” has no checksum`,
      );
    }
    clean[path] = { bytes, sha256: sha256.toLowerCase() };
    total += bytes;
  }
  if (Object.keys(clean).length === 0) {
    throw new AsrError('modelManifestInvalid', 'The model manifest lists no files');
  }

  const declared = Number(manifest.modelBytes);
  return {
    name: String(manifest.name ?? 'whisper-tiny'),
    version: String(manifest.version ?? 'v1'),
    // Trust the file list over the summary: the list is what gets verified.
    modelBytes: Number.isFinite(declared) && declared > 0 ? declared : total,
    files: clean,
  };
}

/**
 * Flatten the manifest into the list of downloads, in manifest order.
 *
 * @param {ReturnType<typeof parseManifest>} manifest
 * @param {string} [root]
 * @returns {Array<{ path: string, url: string, bytes: number, sha256: string }>}
 */
export function manifestFiles(manifest, root = MODEL_FILES_URL) {
  return Object.entries(manifest?.files ?? {}).map(([path, entry]) => ({
    path,
    url: modelFileUrl(path, root),
    bytes: entry.bytes,
    sha256: entry.sha256,
  }));
}

/**
 * Total number of bytes the model occupies once installed.
 *
 * @param {ReturnType<typeof parseManifest>} manifest
 * @returns {number}
 */
export function manifestBytes(manifest) {
  return manifestFiles(manifest).reduce((sum, file) => sum + file.bytes, 0);
}

/**
 * SHA-256 of a buffer as lowercase hex.
 *
 * @param {ArrayBuffer|Uint8Array} data
 * @param {Crypto} [cryptoImpl]
 * @returns {Promise<string>}
 */
export async function sha256Hex(data, cryptoImpl = globalThis.crypto) {
  const subtle = cryptoImpl?.subtle;
  if (!subtle?.digest) {
    throw new AsrError('modelUnsupported', 'This browser cannot verify the model checksum');
  }
  const bytes = data instanceof Uint8Array ? data : new Uint8Array(data);
  const digest = await subtle.digest('SHA-256', bytes);
  return Array.from(new Uint8Array(digest))
    .map((value) => value.toString(16).padStart(2, '0'))
    .join('');
}

/**
 * Read a response body, reporting bytes as they arrive.
 *
 * @param {Response} response
 * @param {{ onBytes?: (received: number) => void, signal?: AbortSignal|null }} [options]
 * @returns {Promise<Uint8Array>}
 */
async function readBody(response, { onBytes, signal } = {}) {
  if (!response?.body || typeof response.body.getReader !== 'function') {
    const buffer = new Uint8Array(await response.arrayBuffer());
    onBytes?.(buffer.byteLength);
    return buffer;
  }

  const reader = response.body.getReader();
  /** @type {Uint8Array[]} */
  const chunks = [];
  let received = 0;
  try {
    for (;;) {
      if (signal?.aborted) {
        await reader.cancel().catch(() => {});
        throw new AsrError('cancelled', 'Download cancelled');
      }
      const { done, value } = await reader.read();
      if (done) break;
      if (!value || value.byteLength === 0) continue;
      chunks.push(value);
      received += value.byteLength;
      onBytes?.(received);
    }
  } finally {
    reader.releaseLock?.();
  }

  const output = new Uint8Array(received);
  let offset = 0;
  for (const chunk of chunks) {
    output.set(chunk, offset);
    offset += chunk.byteLength;
  }
  return output;
}

/** @param {string} code @param {string} message @param {unknown} [cause] */
const modelError = (code, message, cause) => new AsrError(code, message, cause);

/** Open a cache, returning `null` when CacheStorage is unavailable. */
async function openCache(cachesImpl, name) {
  if (!cachesImpl || typeof cachesImpl.open !== 'function') return null;
  try {
    return await cachesImpl.open(name);
  } catch {
    return null;
  }
}

/**
 * Read the manifest: the cached copy first (so the status is available
 * offline), then the network.
 *
 * @param {{
 *   url?: string,
 *   cachesImpl?: CacheStorage,
 *   fetchImpl?: typeof fetch,
 *   cacheName?: string,
 * }} [options]
 * @returns {Promise<ReturnType<typeof parseManifest>>}
 */
export async function readManifest({
  url = MODEL_MANIFEST_URL,
  cachesImpl = globalThis.caches,
  fetchImpl = globalThis.fetch,
  cacheName = MODEL_CACHE_NAME,
} = {}) {
  const store = await openCache(cachesImpl, cacheName);
  if (store) {
    try {
      const cached = await store.match(url);
      if (cached) return parseManifest(await cached.json());
    } catch (error) {
      // A corrupt cached manifest must not block the network copy.
      console.warn('[model] cached manifest unreadable', error);
    }
  }

  let response;
  try {
    response = await fetchImpl(url, { cache: 'no-store' });
  } catch (error) {
    throw modelError('modelManifestUnavailable', 'Could not read the model manifest', error);
  }
  if (!response?.ok) {
    throw modelError(
      'modelManifestUnavailable',
      `The model manifest answered HTTP ${response?.status ?? 0}`,
    );
  }

  const copy = store ? response.clone() : null;
  const manifest = parseManifest(await response.json());
  if (copy && store) {
    try {
      await store.put(url, copy);
    } catch (error) {
      console.warn('[model] could not cache the manifest', error);
    }
  }
  return manifest;
}

/**
 * Whether a cached response really is the complete file.
 *
 * `content-length` is present on responses stored by `fetch` and on the copies
 * this module writes, so a truncated entry left by an interrupted write can be
 * detected without loading ~30 MB into memory.
 */
function cachedComplete(response, bytes) {
  const header = Number(response?.headers?.get?.('content-length'));
  return !(Number.isFinite(header) && header > 0 && bytes > 0 && header !== bytes);
}

/** Find the file in any of the model caches. */
async function findCached(stores, url, bytes) {
  for (const store of stores) {
    try {
      const hit = await store.match(url);
      if (hit && cachedComplete(hit, bytes)) return hit;
    } catch {
      /* an unreadable cache entry is treated as missing */
    }
  }
  return null;
}

/** Delete one file from every cache (a corrupt copy must not be served again). */
async function purgeFile(url, cachesImpl) {
  for (const name of [MODEL_CACHE_NAME, MODEL_RUNTIME_CACHE]) {
    const store = await openCache(cachesImpl, name);
    if (!store) continue;
    try {
      await store.delete(url);
    } catch {
      /* nothing to delete */
    }
  }
}

/**
 * Inspect what is already on the device.
 *
 * Both caches count: a user who transcribed once has the files in the
 * Transformers.js cache, so the UI must not claim the model is missing then.
 *
 * @param {{
 *   manifest: ReturnType<typeof parseManifest>,
 *   root?: string,
 *   cachesImpl?: CacheStorage,
 * }} options
 * @returns {Promise<{
 *   supported: boolean,
 *   ready: boolean,
 *   complete: number,
 *   total: number,
 *   bytes: number,
 *   cachedBytes: number,
 *   missing: string[],
 * }>}
 */
export async function modelStatus({
  manifest,
  root = MODEL_FILES_URL,
  cachesImpl = globalThis.caches,
}) {
  const files = manifestFiles(manifest, root);
  const bytes = files.reduce((sum, file) => sum + file.bytes, 0);
  const base = {
    supported: true,
    ready: false,
    complete: 0,
    total: files.length,
    bytes,
    cachedBytes: 0,
  };

  if (!cachesImpl || typeof cachesImpl.open !== 'function') {
    return { ...base, supported: false, missing: files.map((file) => file.path) };
  }

  const stores = [];
  for (const name of [MODEL_CACHE_NAME, MODEL_RUNTIME_CACHE]) {
    const store = await openCache(cachesImpl, name);
    if (store) stores.push(store);
  }

  /** @type {string[]} */
  const missing = [];
  let complete = 0;
  let cachedBytes = 0;
  for (const file of files) {
    if (await findCached(stores, file.url, file.bytes)) {
      complete += 1;
      cachedBytes += file.bytes;
    } else {
      missing.push(file.path);
    }
  }

  return { ...base, ready: missing.length === 0, complete, cachedBytes, missing };
}

/**
 * Download, verify and cache every model file.
 *
 * Files are written to the cache only after their checksum matches, so an
 * interrupted or corrupted transfer never looks installed. Progress covers the
 * whole package, in bytes.
 *
 * @param {{
 *   manifest: ReturnType<typeof parseManifest>,
 *   root?: string,
 *   manifestUrl?: string,
 *   cacheName?: string,
 *   cachesImpl?: CacheStorage,
 *   fetchImpl?: typeof fetch,
 *   cryptoImpl?: Crypto,
 *   signal?: AbortSignal|null,
 *   onProgress?: (progress: { loaded: number, total: number, fraction: number, file: string }) => void,
 * }} options
 * @returns {Promise<{ bytes: number, files: number }>}
 */
export async function downloadModel({
  manifest,
  root = MODEL_FILES_URL,
  manifestUrl = MODEL_MANIFEST_URL,
  cacheName = MODEL_CACHE_NAME,
  cachesImpl = globalThis.caches,
  fetchImpl = globalThis.fetch,
  cryptoImpl = globalThis.crypto,
  signal = null,
  onProgress,
} = {}) {
  const files = manifestFiles(manifest, root);
  const store = await openCache(cachesImpl, cacheName);
  if (!store) {
    throw modelError('modelUnsupported', 'This browser cannot store the model for offline use');
  }

  const total = files.reduce((sum, file) => sum + file.bytes, 0);
  let loaded = 0;
  const report = (file) =>
    onProgress?.({ loaded, total, fraction: total > 0 ? Math.min(1, loaded / total) : 0, file });
  report('');

  for (const file of files) {
    if (signal?.aborted) throw modelError('cancelled', 'Download cancelled');

    /** @type {Uint8Array|null} */
    let bytes = null;
    for (let attempt = 0; attempt < 2 && !bytes; attempt += 1) {
      let response;
      try {
        response = await fetchImpl(file.url, {
          cache: attempt === 0 ? 'no-store' : 'reload',
          signal,
        });
      } catch (error) {
        if (signal?.aborted) throw modelError('cancelled', 'Download cancelled');
        throw modelError('modelDownloadFailed', `Could not download ${file.path}`, error);
      }
      if (!response?.ok) {
        throw modelError(
          'modelDownloadFailed',
          `${file.path} answered HTTP ${response?.status ?? 0}`,
        );
      }

      let data;
      try {
        data = await readBody(response, {
          signal,
          onBytes: (received) =>
            onProgress?.({
              loaded: Math.min(total, loaded + received),
              total,
              fraction: total > 0 ? Math.min(1, (loaded + received) / total) : 0,
              file: file.path,
            }),
        });
      } catch (error) {
        if (error?.code) throw error;
        if (signal?.aborted) throw modelError('cancelled', 'Download cancelled');
        throw modelError('modelDownloadFailed', `Could not read ${file.path}`, error);
      }

      const digest = await sha256Hex(data, cryptoImpl);
      if (digest === file.sha256 && (!file.bytes || data.byteLength === file.bytes)) {
        bytes = data;
        break;
      }

      // A stale or truncated cache entry is the likely cause: drop it from
      // every cache so the retry really reaches the network.
      await purgeFile(file.url, cachesImpl);
      if (signal?.aborted) throw modelError('cancelled', 'Download cancelled');
    }

    if (!bytes) {
      throw modelError('modelCorrupt', `${file.path} failed the integrity check`);
    }

    try {
      await store.put(
        file.url,
        new Response(bytes, {
          headers: {
            'content-type': contentTypeFor(file.path),
            'content-length': String(bytes.byteLength),
          },
        }),
      );
    } catch (error) {
      const quota = error?.name === 'QuotaExceededError';
      throw modelError(
        quota ? 'modelNoSpace' : 'modelDownloadFailed',
        quota ? 'Not enough storage for the model' : `Could not store ${file.path}`,
        error,
      );
    }

    loaded += bytes.byteLength;
    report(file.path);
  }

  // Keep the manifest next to the files: the status check reads it offline.
  try {
    await store.put(
      manifestUrl,
      new Response(JSON.stringify(manifest), { headers: { 'content-type': 'application/json' } }),
    );
  } catch (error) {
    console.warn('[model] could not cache the manifest', error);
  }

  return { bytes: loaded, files: files.length };
}

/** Best-effort content type for a cached model file. */
function contentTypeFor(path) {
  if (path.endsWith('.json')) return 'application/json';
  if (path.endsWith('.txt')) return 'text/plain;charset=utf-8';
  return 'application/octet-stream';
}

/**
 * Remove the model from this device. Recordings are untouched; the files are
 * downloaded again the next time a transcription needs them.
 *
 * @param {{ cachesImpl?: CacheStorage }} [options]
 * @returns {Promise<boolean>} whether anything was deleted
 */
export async function clearModel({ cachesImpl = globalThis.caches } = {}) {
  if (!cachesImpl || typeof cachesImpl.delete !== 'function') return false;
  let removed = false;
  for (const name of [MODEL_CACHE_NAME, MODEL_RUNTIME_CACHE]) {
    try {
      removed = (await cachesImpl.delete(name)) || removed;
    } catch {
      /* the cache may not exist */
    }
  }
  return removed;
}

/**
 * Free space the browser reports, or `null` when it cannot tell.
 *
 * @param {StorageManager|undefined} [manager]
 * @returns {Promise<number|null>}
 */
export async function availableBytes(manager = globalThis.navigator?.storage) {
  try {
    const estimate = await manager?.estimate?.();
    const quota = Number(estimate?.quota);
    const usage = Number(estimate?.usage);
    if (!Number.isFinite(quota) || quota <= 0) return null;
    return Math.max(0, quota - (Number.isFinite(usage) ? usage : 0));
  } catch {
    return null;
  }
}

/**
 * Refuse a download that cannot fit, before ~45 MB of mobile data is spent.
 *
 * @param {number} bytes
 * @param {{ manager?: StorageManager, marginBytes?: number }} [options]
 * @returns {Promise<void>}
 */
export async function assertSpace(bytes, { manager, marginBytes = SPACE_MARGIN_BYTES } = {}) {
  const free = await availableBytes(manager);
  if (free !== null && free < bytes + marginBytes) {
    throw modelError('modelNoSpace', 'Not enough storage for the speech model');
  }
}
